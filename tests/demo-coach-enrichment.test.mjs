import assert from 'node:assert/strict';
import { buildDemoTenantSeed } from '../scripts/demo-showcase-dataset.mjs';
import { enrichDemoCoachRecords } from '../scripts/enrich-demo-coach-evidence.mjs';

const seed = buildDemoTenantSeed();
const current = structuredClone(seed);
const race = current.fixtures[0].events[0];
const swimmerId = Object.keys(race.resultsBySwimmer)[0];
const result = race.resultsBySwimmer[swimmerId];
delete result.strokeCount;
result.observations = 'Keep verified coaching note';
const test = current.tests[0];
delete test.repResults[0].overallStrokeCount;
const untouchedTest = current.tests[1];
untouchedTest.repResults[0].overallTime = '99:59';
delete untouchedTest.repResults[0].overallStrokeCount;
const beforeAttendance = JSON.stringify(current.attendance);
const beforeResults = result.resultTime;
const { db, audit } = enrichDemoCoachRecords(current);
assert.equal(JSON.stringify(db.attendance), beforeAttendance);
assert.equal(db.fixtures[0].events[0].resultsBySwimmer[swimmerId].resultTime, beforeResults);
assert.equal(db.fixtures[0].events[0].resultsBySwimmer[swimmerId].observations, 'Keep verified coaching note');
assert.ok(db.fixtures[0].events[0].resultsBySwimmer[swimmerId].strokeCount > 0);
assert.ok(db.tests[0].repResults[0].overallStrokeCount > 0);
assert.equal(db.tests[1].repResults[0].overallStrokeCount, undefined);
assert.ok(db.trainingSessionSets.some(set => ['Back', 'Breast', 'Fly', 'IM'].includes(set.stroke)));
assert.ok(audit.trainingStrokeVariety > 0);
assert.equal(JSON.stringify(current.fixtures[0].events[0].resultsBySwimmer[swimmerId]), JSON.stringify(result));
assert.throws(() => enrichDemoCoachRecords({ __meta: { tenantId: 'production' } }), /Refusing/);
console.log('DEMO_COACH_NONDESTRUCTIVE_ENRICHMENT_OK', audit);
